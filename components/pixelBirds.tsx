// Pixel-art birds, drawn once per family group (see lib/birdGroups.ts) and recoloured per species.
// Style from docs/mockup-v3.html: crisp pixels on a 24x24 grid, a one-pixel dark outline, a darker
// tone along the bottom edge of each part.
//
// Every group has 4 designs: the 4 most recognizable figures of the group, drawn from reference photos
// of a typical species (mallard, goose, swan and diving duck for waterfowl; tawny, eagle-owl, barn and
// little owl for owls...). A species picks the design that matches its shape and passes its own colours.
//
// Colours are a palette of up to 6 hex values, each one a part of the bird:
//   0 body    main plumage (chest / flanks, whatever the bird shows most)
//   1 wing    wings, back and tail
//   2 belly   underparts, throat, light patches
//   3 bill
//   4 legs    legs and feet
//   5 accent  head, crest, cap, mask, eye ring or any marking that stands out
// A shorter array is fine for plain birds: the missing parts are derived from the first ones.
// Exception: the goldfinch design uses the legs slot for its yellow wing bar (its legs use the bill colour).
//
// Grid keys: B A W K L C are the 6 parts, b a w c their shaded tone, k outline, E eye (white on dark
// heads, dark on light ones), e fixed white, ~ water, g perch (branch, post, rock, ground).

