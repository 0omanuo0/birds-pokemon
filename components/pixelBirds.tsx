// The group's name for a family as stored in the data ("TURDIDAE"), or for a group name itself.
export function pixelBirdGroup(familyOrGroup: string): string {
    if (PIXEL_BIRDS[familyOrGroup]) return familyOrGroup;
    const g = groupOf(familyOrGroup);
    return g === OTHER_GROUP || !PIXEL_BIRDS[g] ? FALLBACK_GROUP : g;
}

